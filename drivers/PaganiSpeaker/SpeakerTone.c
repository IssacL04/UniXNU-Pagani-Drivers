/* round(32767 * 10^(-k / 20)), k = 0..19. */
static const int16_t kGain[20] = {32767, 29204, 26028, 23197, 20675, 18426, 16422, 14636, 13045, 11626, 10362, 9235, 8231, 7336,
                                  6538, 5827, 5193, 4628, 4125, 3677};

int32_t speaker_tone_gain(uint32_t atten_db)
{
    if (atten_db > 90) atten_db = 90;
    int32_t g = kGain[atten_db % 20];
    for (uint32_t i = 0; i < atten_db / 20; ++i) g = (g + 5) / 10;   /* every 20 dB a factor of ten */
    return g;
}

int32_t speaker_tone_sine(uint32_t phase)
{
    const uint32_t index = phase >> 24, fraction = (phase >> 8) & 0xffffu;
    const int32_t a = kSine[index], b = kSine[index + 1];
    return a + (int32_t)(((int64_t)(b - a) * fraction) >> 16);
}

void speaker_tone_init(SpeakerTone *t, uint32_t hz, uint32_t ms, uint32_t atten_db, uint32_t rate)
{
    if (hz < 20) hz = 20;
    if (hz > 20000) hz = 20000;
    if (ms < 1) ms = 1;
    if (ms > 10000) ms = 10000;
    if (!rate) rate = 48000;
    t->phase = 0;
    t->step = (uint32_t)((((uint64_t)hz << 32) + rate / 2) / rate);
    t->gain = speaker_tone_gain(atten_db);
    t->frames = (uint32_t)((uint64_t)rate * ms / 1000u);
    t->frame = 0;
    t->fade = rate / 100;                                     /* 10 ms */
    if (t->fade > t->frames / 2) t->fade = t->frames / 2;
}

void speaker_tone_fill(SpeakerTone *t, int16_t *dst, uint32_t frames, uint32_t channels)
{
    for (uint32_t i = 0; i < frames; ++i) {
        int32_t v = 0;
        if (t->frame < t->frames) {
            int64_t s = (int64_t)speaker_tone_sine(t->phase) * t->gain;
            const uint32_t from_end = t->frames - 1u - t->frame, edge = t->frame < from_end ? t->frame : from_end;
            if (t->fade && edge < t->fade) s = s * (int64_t)edge / (int64_t)t->fade;
            v = (int32_t)(s / 32768);
            t->phase += t->step;
            t->frame++;
        }
        for (uint32_t c = 0; c < channels; ++c) dst[(uint64_t)i * channels + c] = (int16_t)v;
    }
}
